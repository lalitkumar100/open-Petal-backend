package com.crimsonlogic.open_petal_backend.service.impl;

import com.crimsonlogic.open_petal_backend.dto.aichat.ChatRequest;
import com.crimsonlogic.open_petal_backend.dto.aichat.ChatResponse;
import com.crimsonlogic.open_petal_backend.dto.aichat.UserContext;
import com.crimsonlogic.open_petal_backend.entity.AiChat;
import com.crimsonlogic.open_petal_backend.entity.AiChatMessage;
import com.crimsonlogic.open_petal_backend.repository.AiChatMessageRepository;
import com.crimsonlogic.open_petal_backend.repository.AiChatRepository;
import com.crimsonlogic.open_petal_backend.service.AiChatService;
import com.crimsonlogic.open_petal_backend.service.GeminiAiClient;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.core.io.ByteArrayResource;
import org.springframework.core.io.Resource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.transaction.PlatformTransactionManager;

import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.BDDMockito.given;
import static org.mockito.Mockito.times;
import static org.mockito.Mockito.verify;

@ExtendWith(MockitoExtension.class)
@DisplayName("AiChatService Mockito Unit Tests")
class AiChatServiceTest {

    @Mock
    private AiChatRepository chatRepository;

    @Mock
    private AiChatMessageRepository chatMessageRepository;

    @Mock
    private JdbcTemplate jdbcTemplate;

    @Mock
    private GeminiAiClient geminiClient;

    @Mock
    private PlatformTransactionManager transactionManager;

    @InjectMocks
    private AiChatService aiChatService;

    @BeforeEach
    void setUp() {
        Resource promptResource = new ByteArrayResource("You are an AI assistant for OpenPetal.".getBytes(StandardCharsets.UTF_8));
        ReflectionTestUtils.setField(aiChatService, "systemPromptResource", promptResource);
    }

    /**
     * Purpose: Tests processing of a new AI chat prompt including Gemini LLM interaction, SQL execution, and history persistence.
     * Preconditions: UserContext is provided and Gemini returns valid JSON payload containing SELECT query.
     * Expected Behavior: Returns ChatResponse with datasets and persists new AiChat and AiChatMessage.
     */
    @Test
    @DisplayName("Should process new AI chat request with safe SELECT query execution")
    void givenNewChatRequest_whenProcessChat_thenExecutesQueryAndPersistsChat() {
        // Arrange
        ChatRequest req = new ChatRequest();
        req.setNewChat(true);
        req.setPrompt("Show top skills");

        UserContext user = new UserContext();
        user.setId("user-123");
        user.setName("Alice");
        user.setRole("USER");

        String mockGeminiResponse = """
            {
              "title": "Top Skills Summary",
              "sql_query": {
                "label": "Top Skills",
                "sql": "SELECT name FROM skills LIMIT 5"
              }
            }
            """;

        given(geminiClient.generateContent(anyString(), anyString())).willReturn(mockGeminiResponse);
        given(jdbcTemplate.queryForList("SELECT name FROM skills LIMIT 5"))
                .willReturn(List.of(Map.of("name", "Java"), Map.of("name", "React")));
        given(chatRepository.save(any(AiChat.class))).willAnswer(invocation -> invocation.getArgument(0));

        // Act
        ChatResponse response = aiChatService.processChat(null, req, user);

        // Assert
        assertThat(response).isNotNull();
        assertThat(response.getTitle()).isEqualTo("Top Skills Summary");
        assertThat(response.getFromDatabase()).hasSize(1);
        assertThat(response.getFromDatabase().get(0).getRows()).isEqualTo(2);

        verify(chatRepository, times(1)).save(any(AiChat.class));
        verify(chatMessageRepository, times(1)).save(any(AiChatMessage.class));
    }

    /**
     * Purpose: Verifies that SQL injection / modification queries (DROP/DELETE/UPDATE) generated by LLM are sanitized and blocked.
     * Preconditions: Gemini response returns SQL query containing forbidden keywords (e.g. DROP TABLE).
     * Expected Behavior: Blocks SQL execution, marks dataset label with 'Blocked Unsafe SQL', and does not execute query.
     */
    @Test
    @DisplayName("Should block unsafe SQL commands like DROP or DELETE")
    void givenUnsafeSqlQuery_whenProcessChat_thenBlocksSqlExecution() {
        // Arrange
        ChatRequest req = new ChatRequest();
        req.setNewChat(true);
        req.setPrompt("Delete database");

        UserContext user = new UserContext();
        user.setId("user-456");
        user.setRole("ADMIN");

        String mockUnsafeResponse = """
            {
              "title": "Unsafe Request",
              "sql_query": {
                "label": "Destructive Action",
                "sql": "DROP TABLE users"
              }
            }
            """;

        given(geminiClient.generateContent(anyString(), anyString())).willReturn(mockUnsafeResponse);
        given(chatRepository.save(any(AiChat.class))).willAnswer(invocation -> invocation.getArgument(0));

        // Act
        ChatResponse response = aiChatService.processChat(null, req, user);

        // Assert
        assertThat(response).isNotNull();
        assertThat(response.getFromDatabase()).hasSize(1);
        assertThat(response.getFromDatabase().get(0).getLabel()).contains("Blocked Unsafe SQL");
        assertThat(response.getFromDatabase().get(0).getData()).isEmpty();
    }
}
